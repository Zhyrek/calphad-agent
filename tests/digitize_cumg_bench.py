"""Real-figure benchmark: ESPEI's dataplot of the Cu-Mg tutorial ZPF data (tests/data/espei_cu_mg/cumg_zpf_points.png)
digitized per (colour, shape) series exactly as the agent does it (digitize_setup -> tick calibration ->
digitize_points with color + shape), scored against the tutorial's ZPF datasets (examples/espei/cu-mg).

    .venv/bin/python -W ignore tests/digitize_cumg_bench.py [outdir] [--zpf] [--colour-only]

Marker colour = the phase whose composition was measured, marker shape = the reference.  All markers are open
(hollow) and overlap heavily.  Per series: recall over all truth points (one-to-one matching; coincident truth
points need one detection each) and over the unique truth positions, precision (detections within the tolerance
of a truth point of the series), mean |dx| and |dT| of the matches.  Tolerance dx 0.01, dT 10 K.  Recall is also given over the visibly distinct
positions (truth points closer than ~3 px = a quarter marker merged: no image method can separate them).

--zpf   also run digitized_to_zpf on the digitized series (phase from the colour; coexisting phases inferred from a
        TDB generated by espei_generate_parameters from the tutorial inputs WITHOUT the ZPF data, one call per
        reference) and score the datasets with tests/espei_cumg_live.py score_zpf (phase, x within 0.015, T within
        15 K, phase set) + the partner check over the two-phase reference points only.
--colour-only   additionally score one colour query per phase (all shapes).
"""
import csv
import json
import re
import shutil
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))
EX = ROOT / "examples" / "espei" / "cu-mg"
IMG = ROOT / "tests" / "data" / "espei_cu_mg" / "cumg_zpf_points.png"

COLOURS = {"LIQUID": "#d2f300", "FCC_A1": "#f4c800", "LAVES_C15": "#c10020", "HCP_A3": "#f13a13"}
SHAPES = {"Bagnoud (1978)": "circle", "Jones (1931)": "triangle_down", "Sahmen (1908)": "square",
          "Urazova (1907)": "diamond"}
DX, DT = 0.01, 10.0
SEP_X, SEP_T = 0.0026, 3.75         # ~3 px in this figure (a quarter marker): closer truth points look like one marker


def truth():
    from espei.datasets import load_datasets, recursive_glob
    from espei_cumg_live import _zpf_points
    return _zpf_points(load_datasets(recursive_glob(str(EX / "input-data" / "zpf"))).all())


def match(tr, det):
    """Maximum one-to-one matching within the tolerance (min total normalised distance among those)."""
    from scipy.optimize import linear_sum_assignment
    if not tr or not det:
        return []
    C = np.full((len(tr), len(det)), 1e6)
    for i, (x, T) in enumerate(tr):
        for j, (u, v) in enumerate(det):
            if abs(u - x) <= DX and abs(v - T) <= DT:
                C[i, j] = ((u - x) / DX) ** 2 + ((v - T) / DT) ** 2
    r, c = linear_sum_assignment(C)
    return [(i, j) for i, j in zip(r, c) if C[i, j] < 1e6]


def distinct(pts):
    """Truth positions that are visibly separate markers (greedy merge of points within SEP_X / SEP_T)."""
    out = []
    for p in sorted(pts):
        if not any(abs(p[0] - q[0]) < SEP_X and abs(p[1] - q[1]) < SEP_T for q in out):
            out.append(p)
    return out


def score(tr, det):
    tr = [tuple(t) for t in tr]
    uniq = sorted(set(tr))
    dist = distinct(uniq)
    m = match(tr, det)
    near = lambda p, pool: any(abs(p[0] - q[0]) <= DX and abs(p[1] - q[1]) <= DT for q in pool)  # noqa: E731
    out = {"n_truth": len(tr), "n_unique": len(uniq), "n_det": len(det), "hits": len(m),
           "hits_unique": len(match(uniq, det)),
           "n_distinct": len(dist), "hits_distinct": len(match(dist, det)), "true_det": sum(near(d, tr) for d in det)}
    out["recall"] = out["hits"] / max(1, len(tr))
    out["recall_unique"] = out["hits_unique"] / max(1, len(uniq))
    out["recall_distinct"] = out["hits_distinct"] / max(1, len(dist))
    out["precision"] = out["true_det"] / max(1, len(det)) if det else float("nan")
    out["mae_x"] = float(np.mean([abs(tr[i][0] - det[j][0]) for i, j in m])) if m else float("nan")
    out["mae_T"] = float(np.mean([abs(tr[i][1] - det[j][1]) for i, j in m])) if m else float("nan")
    return out


def read_csv(path):
    with open(path) as fh:
        return [(float(r["x"]), float(r["y"])) for r in csv.DictReader(fh)]


def run(out: Path, colour_only=False):
    from calphad_tools.agent.tools import UI, ToolBox
    out.mkdir(parents=True, exist_ok=True)
    tb = ToolBox(workdir=str(out), output_dir=str(out / "out"), ui=UI(), python_tool="off")
    text, _, err = tb.call("digitize_setup", {"image": str(IMG)})
    assert not err, text
    nx = int(re.search(r"x0\.\.x(\d+)", text).group(1)) + 1
    ny = int(re.search(r"y0\.\.y(\d+)", text).group(1)) + 1
    assert (nx, ny) == (6, 5), f"ticks found: {nx} x, {ny} y\n{text}"
    axes = {"x": {"ticks": {str(i): round(0.2 * i, 1) for i in range(6)}},
            "y": {"ticks": {str(i): 1400 - 200 * i for i in range(5)}}}
    P = truth()
    series = sorted({(p[0], p[4]) for p in P})
    rows, csvs, texts = [], {}, {}
    t0 = time.time()
    for ph, ref in series:
        name = f"{ph}_{ref.split()[0]}"
        args = {"image": str(IMG), "axes": axes, "color": COLOURS[ph], "shape": SHAPES[ref], "series": name,
                "output_csv": f"{name}.csv"}
        t1 = time.time()
        txt, _, err = tb.call("digitize_points", args)
        texts[name] = txt
        det = [] if err else read_csv(out / "out" / f"{name}.csv")
        if not err:
            csvs[name] = (ph, ref, str(out / "out" / f"{name}.csv"))
        tr = [(p[1], p[2]) for p in P if p[0] == ph and p[4] == ref]
        s = score(tr, det)
        s.update(series=name, shape=SHAPES[ref], error=txt.splitlines()[0][:120] if err else "",
                 seconds=round(time.time() - t1, 1))
        rows.append(s)
    # a query for a colour/shape with no data must return (almost) nothing
    extra = {}
    for nm, args in {"CUMG2_any_blue": {"color": "#00508c"},
                     "HCP_A3_circle": {"color": COLOURS["HCP_A3"], "shape": "circle"},
                     "LAVES_C15_triangle_down": {"color": COLOURS["LAVES_C15"], "shape": "triangle_down"}}.items():
        txt, _, err = tb.call("digitize_points", {"image": str(IMG), "axes": axes, "series": nm,
                                                  "output_csv": f"{nm}.csv", **args})
        extra[nm] = "error: " + txt.splitlines()[0][:100] if err else len(read_csv(out / "out" / f"{nm}.csv"))
    col_rows = []
    if colour_only:
        for ph in COLOURS:
            nm = f"{ph}_colour"
            txt, _, err = tb.call("digitize_points", {"image": str(IMG), "axes": axes, "color": COLOURS[ph],
                                                      "series": nm, "output_csv": f"{nm}.csv"})
            det = [] if err else read_csv(out / "out" / f"{nm}.csv")
            s = score([(p[1], p[2]) for p in P if p[0] == ph], det)
            s["series"] = nm
            col_rows.append(s)
    total = time.time() - t0
    return rows, extra, col_rows, csvs, axes, texts, total


def fmt(rows, title):
    L = [title, f"{'series':24s} {'shape':13s} {'truth':>5s} {'uniq':>4s} {'dist':>4s} {'det':>4s} {'recall':>6s} {'rec_u':>6s} "
                f"{'rec_d':>6s} {'prec':>5s} {'|dx|':>6s} {'|dT|':>5s}"]
    for r in rows:
        L.append(f"{r['series']:24s} {r.get('shape', ''):13s} {r['n_truth']:5d} {r['n_unique']:4d} {r['n_distinct']:4d} "
                 f"{r['n_det']:4d} {r['recall']:6.3f} {r['recall_unique']:6.3f} {r['recall_distinct']:6.3f} "
                 f"{r['precision']:5.2f} {r['mae_x']:6.4f} "
                 f"{r['mae_T']:5.1f}" + (f"  ERROR {r['error']}" if r.get("error") else ""))
    nt, nu, ns, nd = (sum(r[k] for r in rows) for k in ("n_truth", "n_unique", "n_distinct", "n_det"))
    h, hu, hs, td = (sum(r[k] for r in rows) for k in ("hits", "hits_unique", "hits_distinct", "true_det"))
    L.append(f"{'OVERALL':24s} {'':13s} {nt:5d} {nu:4d} {ns:4d} {nd:4d} {h / nt:6.3f} {hu / nu:6.3f} {hs / ns:6.3f} "
             f"{td / max(1, nd):5.2f}")
    return "\n".join(L)


# ------------------------------------------------------------------------------------------------ ZPF part
def make_tdb(out: Path) -> Path:
    """Parameters from the tutorial's non-ZPF inputs (ESPEI generation does not use ZPF data)."""
    gen = out / "gen"
    tdb = gen / "out" / "espei_runs" / "cumg" / "dft.tdb"
    if tdb.exists():
        return tdb
    from test_espei_run import _make_tb, call
    gen.mkdir(parents=True, exist_ok=True)
    shutil.copytree(EX, gen / "cu-mg", dirs_exist_ok=True)
    shutil.rmtree(gen / "cu-mg" / "input-data" / "zpf")
    tb = _make_tb(gen)
    call(tb, "espei_generate_parameters", {"name": "cumg", "espei_input": "cu-mg/run_param_gen.yaml"})
    assert tdb.exists(), f"no TDB at {tdb}"
    return tdb


def zpf(out: Path, csvs, axes):
    from calphad_tools.agent.tools import UI, ToolBox
    from espei_cumg_live import score_zpf
    tdb = make_tdb(out)
    work = out / "zpfwork"
    if work.exists():
        shutil.rmtree(work)
    (work / "input-data" / "zpf").mkdir(parents=True)
    tb = ToolBox(workdir=str(work), output_dir=str(out / "zout"), ui=UI(), python_tool="off")
    by_ref = {}
    for name, (ph, ref, path) in csvs.items():
        by_ref.setdefault(ref, []).append((name, ph, path))
    texts = {}
    for ref, items in sorted(by_ref.items()):
        args = {"components": ["CU", "MG"], "csv": [p for _, _, p in items], "image": str(IMG), "axes": axes,
                "assignments": {name: {"phase": ph} for name, ph, _ in items}, "tdb": str(tdb),
                "reference": ref, "output_dir": str(work / "input-data" / "zpf"),
                "prefix": ref.split()[0].lower()}
        txt, _, err = tb.call("digitized_to_zpf", args)
        texts[ref] = txt
        if err:
            print(f"digitized_to_zpf ERROR for {ref}: {txt[:600]}")
    sc = score_zpf(work)
    sc.update(two_phase_partners(work))
    return sc, texts, tdb


def two_phase_partners(work: Path) -> dict:
    """score_zpf's partner check restricted to reference points measured in a two-phase equilibrium: 54 of the
    292 are single-phase observations (Jones' FCC solubility, Bagnoud's LAVES_C15 homogeneity), which a figure of
    markers does not distinguish from boundary points."""
    from espei.datasets import load_datasets, recursive_glob
    from espei_cumg_live import _zpf_points
    mine = _zpf_points(load_datasets(recursive_glob(str(work / "input-data" / "zpf"))).all())
    ref = [p for p in truth() if len(p[3]) >= 2]
    ok = n = 0
    for p in ref:
        c = [q for q in mine if q[0] == p[0] and abs(q[1] - p[1]) <= 0.015 and abs(q[2] - p[2]) <= 15]
        if c:
            q = min(c, key=lambda q: ((q[1] - p[1]) / 0.015) ** 2 + ((q[2] - p[2]) / 15) ** 2)
            n += 1
            ok += p[3] == q[3]
    return {"ref_points_two_phase": len(ref), "partners_correct_two_phase": round(ok / max(n, 1), 3),
            "single_phase_ref_points": sum(1 for p in truth() if len(p[3]) == 1)}


def main():
    a = [x for x in sys.argv[1:] if not x.startswith("--")]
    out = Path(a[0] if a else ROOT / "calphad_outputs" / "digitize_cumg_bench").resolve()
    rows, extra, col_rows, csvs, axes, texts, total = run(out, colour_only="--colour-only" in sys.argv)
    print(fmt(rows, f"Cu-Mg dataplot, per (colour, shape) series, tolerance dx {DX} dT {DT} K  ({total:.0f} s)"))
    print("queries without data (detections):", extra)
    if col_rows:
        print(fmt(col_rows, "colour-only queries (all shapes of the phase)"))
    (out / "bench.json").write_text(json.dumps({"series": rows, "extra": extra, "colour": col_rows}, indent=1))
    (out / "texts.json").write_text(json.dumps(texts, indent=1))
    if "--zpf" in sys.argv:
        sc, ztexts, tdb = zpf(out, csvs, axes)
        print(f"\nZPF datasets via digitized_to_zpf (TDB {tdb.relative_to(out)}):")
        print(json.dumps(sc, indent=1))
        (out / "zpf_texts.json").write_text(json.dumps(ztexts, indent=1))


if __name__ == "__main__":
    main()
